const CV = LEARNING_BENCHMARK_V2_CORPUS_VERSION;

function observation(
  overrides: Partial<LearningBenchmarkV2FixtureObservationInput> & { observationId: string },
): LearningBenchmarkV2FixtureObservationInput {
  return {
    resolverRunId: `${overrides.observationId}-run`,
    rawInput: 'benchmark fixture raw input',
    normalizedInput: 'benchmark fixture raw input',
    locale: 'de',
    inputType: 'generic',
    outcome: 'accepted',
    candidateCount: 1,
    selectedSource: { type: 'bls' },
    provenanceStatus: 'source_grounded',
    resolverVersion: 'learning-benchmark-v2-fixture-resolver-v1',
    totalLatencyMs: 10,
    reasonCodes: [],
    occurredAt: '2026-01-01T00:00:00.000Z',
    ...overrides,
  };
}

const routingPayload = (sourceType: 'bls' | 'off' | 'usda' = 'bls') => ({
  type: 'source-routing-pattern' as const,
  locale: 'de' as const,
  inputType: 'generic',
  sourceType,
});

const negativeRoutingPayload = (
  sourceType: 'bls' | 'off' | 'usda' = 'bls',
  reasonCode: 'NO_CANDIDATES' | 'LOW_SCORE' = 'LOW_SCORE',
) => ({
  type: 'negative-source-routing-rule' as const,
  locale: 'de' as const,
  inputType: 'generic',
  sourceType,
  reasonCode,
});

